CREATE TABLE IF NOT EXISTS m_items (
    id BINARY(16) NOT NULL COMMENT 'ID',
    name VARCHAR(50) NOT NULL COMMENT 'アイテム名',
    description VARCHAR(150) NOT NULL COMMENT '説明',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '作成日時',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新日時',
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='アイテム';
