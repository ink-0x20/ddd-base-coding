CREATE TABLE IF NOT EXISTS m_main_stories (
    id BINARY(16) NOT NULL COMMENT 'ID',
    name VARCHAR(50) NOT NULL COMMENT 'ストーリー名',
    chapter INT UNSIGNED NOT NULL COMMENT 'チャプター',
    episode INT UNSIGNED NOT NULL COMMENT 'エピソード',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '作成日時',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新日時',
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='メインストーリー';
