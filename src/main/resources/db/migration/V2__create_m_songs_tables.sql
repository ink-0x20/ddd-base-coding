CREATE TABLE IF NOT EXISTS m_songs (
    id CHAR(8) NOT NULL COMMENT 'ID',
    name VARCHAR(50) NOT NULL COMMENT '楽曲名',
    easy_level TINYINT(2) UNSIGNED NOT NULL COMMENT 'easy楽曲Lv',
    normal_level TINYINT(2) UNSIGNED NOT NULL COMMENT 'normal楽曲Lv',
    hard_level TINYINT(2) UNSIGNED NOT NULL COMMENT 'hard楽曲Lv',
    expert_level TINYINT(2) UNSIGNED NOT NULL COMMENT 'expert楽曲Lv',
    unlock_type TINYINT(1) UNSIGNED NOT NULL DEFAULT 0 COMMENT '解放条件',
    unlock_target_id BINARY(16) NULL DEFAULT NULL COMMENT '解放に必要な対象ID',
    unlock_quantity TINYINT(1) UNSIGNED NOT NULL DEFAULT 0 COMMENT '解放に必要な数',
    publish_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '公開日時',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '作成日時',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新日時',
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='楽曲';
